"""Rebuild the embedded, historical climate colour image (requires Pillow and NumPy)."""
from pathlib import Path
from PIL import Image, ImageFilter
import hashlib, json, base64, io
import numpy as np
ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'koppen-geiger-1991-2020.tif'
DRY = np.array([239, 241, 230], dtype=float)  # Existing global crop colour.
WET = np.array([202, 235, 215], dtype=float)
# 0=no-data; 1..30 are the published Beck et al. climate classes.
# Summer-dry and arid climates retain the current neutral crop palette.
WEIGHTS = [0, 1, 1, .45, 0, 0, 0, 0, 0, .06, .15,
           .65, .7, .5, 1, 1, .9, .1, .15, .2, .15,
           .65, .85, .65, .35, 1, 1, .8, .5, .15, 0]
recipe = dict(sourceSha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
              dry=DRY.tolist(), wet=WET.tolist(), weights=WEIGHTS,
              blurDegrees=.25, maxzoom=4, tileSize=256, period='1991–2020')
digest = hashlib.sha256(json.dumps(recipe, sort_keys=True).encode()).hexdigest()[:24]
classes = np.asarray(Image.open(SOURCE))
assert classes.shape == (1800, 3600) and classes.max() <= 30
valid = classes > 0
signal = np.take(WEIGHTS, classes)
# Normalize the blur by valid land so coastlines do not artificially dry out.
blur = lambda a: np.asarray(Image.fromarray(np.uint8(np.round(a * 255))).filter(
    ImageFilter.GaussianBlur(2.5)), dtype=float) / 255
smoothed = np.divide(blur(signal), blur(valid), out=np.zeros_like(signal),
                     where=blur(valid) > .01).clip(0, 1)
colour = np.uint8(np.round(DRY + smoothed[..., None] * (WET - DRY)))
# Project the global 0.1 degree grid to Web Mercator before making XYZ tiles.
size = 4096
latitude = np.degrees(np.arctan(np.sinh(np.pi * (1 - 2 * (np.arange(size) + .5) / size))))
row = (90 - latitude) * 10 - .5
low = np.floor(row).astype(int).clip(0, 1798)
fraction = (row - low).clip(0, 1)
projected = np.uint8(np.round(colour[low] * (1 - fraction[:, None, None]) +
                             colour[low + 1] * fraction[:, None, None]))
world = Image.fromarray(projected).resize((size, size), Image.Resampling.BILINEAR)
buffer = io.BytesIO()
world.save(buffer, format='PNG', optimize=True)
uri = 'data:image/png;base64,' + base64.b64encode(buffer.getvalue()).decode()
output = ROOT / '../../../src/official/streets-climate-image.ts'
output.write_text('// Generated by assets/streets/climate/build.py. See its NOTICE.txt.\nexport const streetsClimateImage = ' + json.dumps(uri) + ';\n')
(ROOT / 'recipe.json').write_text(json.dumps(recipe, indent=2)+'\n')
# Keep generated sources reproducible under the package formatter.
import subprocess
subprocess.run(['pnpm', 'exec', 'prettier', '--write', str(output.resolve()), str(ROOT / 'recipe.json')], cwd=ROOT.parents[4], check=True)
print(json.dumps({'imageBytes':len(buffer.getvalue()), 'sourceSha256':recipe['sourceSha256']}))
