import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {format, resolveConfig} from 'prettier';
import {readSpecification} from './mobile-style.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(resolve(root, 'packages/dev/package.json'));
const manifest = require.resolve('@maplibre/maplibre-gl-style-spec/package.json');
const {version} = JSON.parse(await readFile(manifest, 'utf8'));
const spec = JSON.parse(await readFile(resolve(dirname(manifest), 'dist/latest.json'), 'utf8'));
const {layers} = readSpecification(spec);
const target = resolve(root, 'packages/react-native/src/style-spec.ts');

function baseType(property) {
  if (['number', 'string', 'boolean'].includes(property.type)) return property.type;
  if (['color', 'formatted', 'resolvedImage'].includes(property.type)) return 'string';
  if (property.type === 'enum') return Object.keys(property.values).map(JSON.stringify).join(' | ');
  if (property.type === 'padding') return 'number | readonly number[]';
  if (property.type === 'numberArray') return 'readonly number[]';
  if (property.type === 'variableAnchorOffsetCollection')
    return 'readonly (string | readonly number[])[]';
  if (property.type === 'colorArray') return 'readonly string[]';
  if (property.type === 'array') {
    const type = baseType({...property, type: property.value});
    return 'readonly (' + type + ')[]';
  }
  throw new Error('Unsupported native style property type ' + property.type);
}

let source =
  '// Generated by scripts/mobile-react-native-style.mjs from style-spec ' +
  version +
  '.\n' +
  "import type {Expression} from './contract';\n\n";
const mapping = {};
for (const layer of layers) {
  const name = layer.type
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
  source += 'export type ' + name + 'LayerStyle = Readonly<{\n';
  mapping[layer.type] = {};
  for (const property of layer.properties) {
    source += '  ' + property.identifier + '?: ' + baseType(property.property) + ' | Expression;\n';
    mapping[layer.type][property.identifier] = {name: property.name, group: property.kind};
    if (property.transition) {
      const transition = property.identifier + 'Transition';
      source += '  ' + transition + '?: Readonly<{duration?: number; delay?: number}>;\n';
      mapping[layer.type][transition] = {name: property.name + '-transition', group: property.kind};
    }
  }
  source += '}>;\n\n';
}
source += 'export const layerProperties = ' + JSON.stringify(mapping) + ' as const;\n';
const output = await format(source, {...(await resolveConfig(target)), parser: 'typescript'});
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8').catch(() => '')) !== output)
    throw new Error('Regenerate with node scripts/mobile-react-native-style.mjs.');
} else {
  await writeFile(target, output);
}
