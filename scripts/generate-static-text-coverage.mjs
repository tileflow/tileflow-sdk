import * as fontkit from 'fontkit';
import {createHash} from 'node:crypto';
import {readdirSync} from 'node:fs';
import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {format} from 'prettier';

const require = createRequire(import.meta.url);
const outputUrl = new URL('../packages/static/src/text-coverage.generated.ts', import.meta.url);
const check = process.argv.includes('--check');
const commonFontSpecifiers = [
  '@fontsource/noto-sans/files/noto-sans-latin-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-latin-ext-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-vietnamese-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-greek-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-greek-ext-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-cyrillic-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-cyrillic-ext-400-normal.woff2',
  '@fontsource/noto-sans/files/noto-sans-devanagari-400-normal.woff2',
  '@fontsource/noto-sans-arabic/files/noto-sans-arabic-arabic-400-normal.woff2',
  '@fontsource/noto-sans-hebrew/files/noto-sans-hebrew-hebrew-400-normal.woff2',
  '@fontsource/noto-sans-thai/files/noto-sans-thai-thai-400-normal.woff2',
];
const cjkPackages = [
  ['@fontsource/noto-sans-jp', 'noto-sans-jp', 'japanese'],
  ['@fontsource/noto-sans-sc', 'noto-sans-sc', 'chinese-simplified'],
  ['@fontsource/noto-sans-tc', 'noto-sans-tc', 'chinese-traditional'],
  ['@fontsource/noto-sans-kr', 'noto-sans-kr', 'korean'],
];
const fontSpecifiers = [
  ...commonFontSpecifiers,
  ...cjkPackages.flatMap(([packageName, prefix, subset]) =>
    numberedCjkSpecifiers(packageName, prefix, subset),
  ),
];

const codePoints = new Set();
for (const specifier of fontSpecifiers) {
  const font = fontkit.openSync(require.resolve(specifier));
  for (const codePoint of font.characterSet) {
    if (font.glyphForCodePoint(codePoint).id !== 0 && isSafeStaticTextCodePoint(codePoint)) {
      codePoints.add(codePoint);
    }
  }
}

const ordered = [...codePoints].sort((left, right) => left - right);
const maximum = ordered.at(-1) ?? 0;
const bytes = new Uint8Array(Math.ceil((maximum + 1) / 8));
for (const codePoint of ordered) bytes[codePoint >> 3] |= 1 << (codePoint & 7);
const base64 = Buffer.from(bytes).toString('base64');
const sha256 = createHash('sha256').update(bytes).digest('hex');
const source = await format(
  `// Generated by scripts/generate-static-text-coverage.mjs. Do not edit.\n\nexport const staticTextCoverageBase64 = '${base64}';\nexport const staticTextCoverageMaximumCodePoint = ${maximum};\nexport const staticTextCoveragePointCount = ${ordered.length};\nexport const staticTextCoverageSha256 = '${sha256}';\n`,
  {
    bracketSpacing: false,
    filepath: fileURLToPath(outputUrl),
    printWidth: 100,
    singleQuote: true,
    trailingComma: 'all',
  },
);

if (check) {
  const current = await readFile(outputUrl, 'utf8').catch(() => '');
  if (current !== source) {
    console.error(`${fileURLToPath(outputUrl)} is stale. Run pnpm static-text:generate.`);
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, source);
}

function isSafeStaticTextCodePoint(codePoint) {
  const value = String.fromCodePoint(codePoint);
  if (/\p{Cc}|\p{Cs}|\p{Co}|\p{Zl}|\p{Zp}/u.test(value)) return false;
  if (/\p{Emoji_Presentation}/u.test(value)) return false;
  if (codePoint >= 0xfdd0 && codePoint <= 0xfdef) return false;
  if ((codePoint & 0xffff) === 0xfffe || (codePoint & 0xffff) === 0xffff) return false;
  if (codePoint === 0x20e3 || codePoint === 0xfe0f) return false;
  if (codePoint >= 0x1f1e6 && codePoint <= 0x1f1ff) return false;
  if (codePoint >= 0xe0020 && codePoint <= 0xe007f) return false;
  return true;
}

function numberedCjkSpecifiers(packageName, prefix, subset) {
  const directory = dirname(
    require.resolve(`${packageName}/files/${prefix}-${subset}-400-normal.woff2`),
  );
  return readdirSync(directory)
    .map((name) => ({match: name.match(new RegExp(`^${prefix}-(\\d+)-400-normal\\.woff2$`)), name}))
    .filter(({match}) => match)
    .sort((left, right) => Number(left.match[1]) - Number(right.match[1]))
    .map(({name}) => `${packageName}/files/${name}`);
}
