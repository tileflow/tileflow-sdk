import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {format, resolveConfig} from 'prettier';
import {
  tileflowWorldAllLanguagesMinZoom,
  tileflowWorldLayerFields,
  type TileflowWorldLayerName,
  tileflowWorldLayers,
  tileflowWorldLayerZooms,
  tileflowWorldNameLanguagePrefix,
  tileflowWorldOverviewLanguages,
  tileflowWorldSchemaVersion,
  tileflowWorldTilesetOf,
  tileflowWorldVocabularies,
} from '../src/data/tileflow-world-schema';

const schemaPath = fileURLToPath(new URL('../reference/tileflow-world-v1.json', import.meta.url));

/** The machine-readable Tileflow World schema, published under CC0 1.0. */
export function createTileflowWorldSchemaContract(): Record<string, unknown> {
  const names = (Object.keys(tileflowWorldLayers) as TileflowWorldLayerName[]).sort((a, b) =>
    tileflowWorldLayers[a] < tileflowWorldLayers[b] ? -1 : 1,
  );
  return {
    $comment:
      'Generated by packages/core/scripts/generate-world-schema.ts from packages/core/src/data/tileflow-world-schema.ts.',
    id: 'tileflow-world',
    version: tileflowWorldSchemaVersion,
    license: {
      id: 'CC0-1.0',
      url: 'https://creativecommons.org/publicdomain/zero/1.0/',
      statement:
        'This schema is dedicated to the public domain. Using it needs no attribution. Data in tiles that follow it keeps its own credits.',
    },
    encoding: {
      container: 'pmtiles-v3',
      tiles: 'mvt',
      compression: 'gzip',
      minzoom: 0,
      maxzoom: 15,
    },
    names: {
      local: 'name',
      latin: 'name_latin',
      language: `${tileflowWorldNameLanguagePrefix}<BCP 47 code>`,
      overviewLanguages: [...tileflowWorldOverviewLanguages],
      allLanguagesMinZoom: tileflowWorldAllLanguagesMinZoom,
    },
    layers: Object.fromEntries(
      names.map((name) => {
        const zooms = (tileflowWorldLayerZooms as Partial<Record<string, readonly number[]>>)[name];
        const values = (tileflowWorldVocabularies as Partial<Record<string, unknown>>)[name];
        return [
          tileflowWorldLayers[name],
          {
            tileset: tileflowWorldTilesetOf(name),
            ...(zooms ? {minzoom: zooms[0], maxzoom: zooms[1]} : {}),
            fields: tileflowWorldLayerFields[name],
            ...(values ? {values} : {}),
          },
        ];
      }),
    ),
  };
}

async function main(mode: string | undefined): Promise<void> {
  const source = JSON.stringify(createTileflowWorldSchemaContract());
  const expected = await format(source, {
    ...(await resolveConfig(schemaPath)),
    filepath: schemaPath,
  });
  if (mode === '--write') {
    await writeFile(schemaPath, expected, 'utf8');
    return;
  }
  if (mode !== '--check') throw new Error('Usage: generate-world-schema.ts --check | --write');
  const actual = await readFile(schemaPath, 'utf8').catch(() => '');
  if (actual !== expected) {
    throw new Error('reference/tileflow-world-v1.json is stale; run pnpm reference:generate.');
  }
}

await main(process.argv[2]);
