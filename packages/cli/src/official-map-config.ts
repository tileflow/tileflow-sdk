import {mkdir, readFile, rename, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname, join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

/** The official maps that preview and capture can open without a project config. */
export const tileflowOfficialMapNames = Object.freeze([
  'outdoors',
  'soundings',
  'streets',
] as const);
export type TileflowOfficialMapName = (typeof tileflowOfficialMapNames)[number];

export function isTileflowOfficialMapName(value: string): value is TileflowOfficialMapName {
  return (tileflowOfficialMapNames as readonly string[]).includes(value);
}

const require = createRequire(import.meta.url);

/**
 * Writes a config that extends one official map, under the project's `.tileflow/cache`, and returns
 * its path. Its imports name the exact `@tileflow/core` and `@tileflow/maps` this CLI runs with, so
 * an official map opens in an empty directory without installing anything.
 */
export async function writeTileflowOfficialMapConfig(
  name: TileflowOfficialMapName,
  cwd: string,
): Promise<string> {
  const core = pathToFileURL(require.resolve('@tileflow/core')).href;
  const maps = pathToFileURL(require.resolve('@tileflow/maps')).href;
  const source = `// Generated by tileflow for the official ${name} map; safe to delete.
import {defineMap} from ${JSON.stringify(core)};
import {${name}} from ${JSON.stringify(maps)};

export default defineMap({id: ${JSON.stringify(name)}, name: ${JSON.stringify(officialLabel(name))}, version: 1, extends: ${name}});
`;
  const path = resolve(cwd, '.tileflow', 'cache', 'official-maps', `${name}.config.mjs`);
  const current = await readFile(path, 'utf8').catch(() => undefined);
  if (current !== source) {
    await mkdir(dirname(path), {recursive: true});
    const staged = join(dirname(path), `.${name}.config.${process.pid}.tmp`);
    await writeFile(staged, source, 'utf8');
    await rename(staged, path);
  }
  return path;
}

function officialLabel(name: TileflowOfficialMapName): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}
