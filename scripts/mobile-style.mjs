// Renders the typed runtime style of the Swift and Kotlin SDKs from the MapLibre style
// specification that the embedded renderer's MapLibre GL JS ships: a layer type for each of its
// layer kinds with every layout and paint property, the enumerations those properties take, and a
// factory for each expression operator. scripts/mobile-style-generate.mjs writes or checks the
// outputs; this module stays free of file access so its rules can be tested directly.
import {documentation} from './mobile-protocol.mjs';

export const banner = (version) =>
  `// Generated by scripts/mobile-style-generate.mjs from the MapLibre style specification ${version}.\n// Edit the generator, then regenerate.\n`;

export const outputs = {
  swiftLayers: 'platforms/ios/Sources/Tileflow/Style/StyleLayers.swift',
  swiftExpressions: 'platforms/ios/Sources/Tileflow/Style/StyleExpressions.swift',
  kotlinLayers: 'platforms/android/tileflow/src/main/java/dev/tileflow/sdk/StyleLayers.kt',
  kotlinExpressions:
    'platforms/android/tileflow/src/main/java/dev/tileflow/sdk/StyleExpressions.kt',
};

/** Layer kinds whose source can be a vector tileset, so they take a source layer and a filter. */
const featureLayers = new Set(['fill', 'line', 'symbol', 'circle', 'heatmap', 'fill-extrusion']);

/**
 * Operators whose names are not identifiers, or are keywords in Swift or Kotlin, take the names
 * the Mapbox Maps SDKs use, the same on both platforms.
 */
export const operatorNames = {
  '+': 'sum',
  '*': 'product',
  '-': 'subtract',
  '/': 'division',
  '%': 'mod',
  '^': 'pow',
  '==': 'eq',
  '!=': 'neq',
  '>': 'gt',
  '<': 'lt',
  '>=': 'gte',
  '<=': 'lte',
  '!': 'not',
  case: 'switchCase',
  let: 'letExpression',
  var: 'varExpression',
  in: 'inExpression',
  object: 'objectExpression',
  typeof: 'typeofExpression',
};
/** Operators written by hand because their argument is a JSON value, not an expression. */
const handWritten = new Set(['literal']);

const words = (name) => name.split(/[^A-Za-z0-9]+/u).filter(Boolean);
/** `fill-extrusion` → `FillExtrusion`. */
export const pascal = (name) =>
  words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join('');
/** `circle-radius` → `circleRadius`. */
export const camel = (name) => {
  const value = pascal(name);
  return value[0].toLowerCase() + value.slice(1);
};
/** `top-left` → `TOP_LEFT`. */
const constant = (name) =>
  words(name)
    .map((word) => word.toUpperCase())
    .join('_');
export const operatorName = (name) => operatorNames[name] ?? camel(name);
export const layerTypeName = (type) => `Tileflow${pascal(type)}Layer`;
export const enumTypeName = (property) => `Tileflow${pascal(property)}`;

/** The specification's prose as one sentence or paragraph for a documentation comment. */
export function prose(text) {
  return (text ?? '')
    .split(/\n\s*\n/u)[0]
    .replaceAll(/\[([^\]]+)\]\([^)]*\)/gu, '$1')
    .replaceAll(/\s+/gu, ' ')
    .replaceAll('*/', '*&#47;')
    .trim();
}

function describeProperty(property) {
  const parts = [prose(property.doc)];
  if (property.units) parts.push(`In ${property.units}.`);
  if (property.minimum !== undefined && property.maximum !== undefined)
    parts.push(`From ${property.minimum} to ${property.maximum}.`);
  else if (property.minimum !== undefined) parts.push(`At least ${property.minimum}.`);
  if (property.default !== undefined)
    parts.push(`Default: \`${JSON.stringify(property.default)}\`.`);
  if (!property.expression) parts.push('Takes a constant only.');
  return parts.filter(Boolean).join(' ');
}

/** The constant type of a property on each platform. */
export function valueType(name, property) {
  const scalar = {
    number: ['Double', 'Double'],
    boolean: ['Bool', 'Boolean'],
    string: ['String', 'String'],
    formatted: ['String', 'String'],
    resolvedImage: ['String', 'String'],
    color: ['TileflowColor', 'TileflowColor'],
    padding: ['[Double]', 'List<Double>'],
    numberArray: ['[Double]', 'List<Double>'],
    colorArray: ['[TileflowColor]', 'List<TileflowColor>'],
    variableAnchorOffsetCollection: ['TileflowTextAnchorOffsets', 'TileflowTextAnchorOffsets'],
    enum: [enumTypeName(name), enumTypeName(name)],
  };
  if (property.type === 'array') {
    const [swift, kotlin] =
      property.value === 'enum' ? [enumTypeName(name), enumTypeName(name)] : scalar[property.value];
    if (!swift) throw new Error(`Unsupported array of ${property.value} for ${name}.`);
    return {swift: `[${swift}]`, kotlin: `List<${kotlin}>`};
  }
  const types = scalar[property.type];
  if (!types) throw new Error(`Unsupported property type ${property.type} for ${name}.`);
  return {swift: types[0], kotlin: types[1]};
}

/** Every layer kind with its layout and paint properties, in the specification's order. */
export function readSpecification(spec) {
  const layers = Object.entries(spec.layer.type.values).map(([type, value]) => {
    const group = (kind) =>
      Object.entries(spec[`${kind}_${type}`] ?? {}).map(([name, property]) => ({
        name,
        kind,
        property,
        identifier: camel(name),
        type: valueType(name, property),
        expression: Boolean(property.expression),
        transition: property.transition === true,
        documentation: describeProperty(property),
      }));
    return {
      type,
      name: layerTypeName(type),
      documentation: prose(value.doc),
      source: type !== 'background',
      features: featureLayers.has(type),
      properties: [...group('layout'), ...group('paint')],
    };
  });
  const enums = new Map();
  for (const layer of layers)
    for (const {name, property} of layer.properties) {
      if (!property.values) continue;
      const values = Object.entries(property.values).map(([value, entry]) => ({
        value,
        documentation: prose(entry.doc),
      }));
      const key = enumTypeName(name);
      const known = enums.get(key);
      if (
        known &&
        JSON.stringify(known.values.map((v) => v.value)) !==
          JSON.stringify(values.map((v) => v.value))
      )
        throw new Error(`${name} takes different values in different layers.`);
      if (!known) enums.set(key, {name: key, property: name, values});
    }
  const operators = Object.entries(spec.expression_name.values)
    .filter(([name]) => !handWritten.has(name))
    .map(([name, value]) => ({
      name,
      identifier: operatorName(name),
      documentation: prose(value.doc),
    }));
  const interpolations = Object.entries(spec.interpolation_name?.values ?? {}).map(
    ([name, value]) => ({name, identifier: camel(name), documentation: prose(value.doc)}),
  );
  const identifiers = [...operators, ...interpolations].map((operator) => operator.identifier);
  if (new Set(identifiers).size !== identifiers.length)
    throw new Error('Two expression operators share a name.');
  return {
    version: spec.$version === 8 ? undefined : spec.$version,
    layers,
    enums: [...enums.values()],
    operators,
    interpolations,
  };
}

const swiftDoc = (text, indent) => documentation(text, indent, 'swift');
const kotlinDoc = (text, indent) => documentation(text, indent, 'kotlin');
const swiftCase = (value) => {
  const name = camel(value);
  return ['default', 'case', 'in', 'is', 'as', 'self'].includes(name) ? `\`${name}\`` : name;
};

function swiftLayers(model, version) {
  const enums = model.enums.map(
    (entry) => `${swiftDoc(`Values of \`${entry.property}\`.`, '')}
public enum ${entry.name}: String, Sendable, Equatable, CaseIterable {
${entry.values
  .map(
    (value) =>
      `${value.documentation ? `${swiftDoc(value.documentation, '  ')}\n` : ''}  case ${swiftCase(value.value)} = ${JSON.stringify(value.value)}`,
  )
  .join('\n')}
}

extension ${entry.name}: StyleWire {}`,
  );
  const layers = model.layers.map((layer) => {
    const fields = [
      '  public var id: String',
      ...(layer.source
        ? [
            `${swiftDoc('The application source the layer draws.', '  ')}\n  public var source: String`,
          ]
        : []),
      ...(layer.features
        ? [
            `${swiftDoc('The layer of a vector source to draw.', '  ')}\n  public var sourceLayer: String?`,
            `${swiftDoc('Draws only the features this expression accepts.', '  ')}\n  public var filter: TileflowExpression?`,
          ]
        : []),
      `${swiftDoc('The zoom level from which the layer shows.', '  ')}\n  public var minZoom: Double?`,
      `${swiftDoc('The zoom level from which the layer hides.', '  ')}\n  public var maxZoom: Double?`,
      `${swiftDoc('Where the layer lies among the map’s own layers; nil lies above them all.', '  ')}\n  public var slot: TileflowLayerSlot?`,
    ];
    const properties = layer.properties.flatMap((entry) => {
      const type = entry.expression ? `TileflowValue<${entry.type.swift}>` : entry.type.swift;
      return [
        `${swiftDoc(entry.documentation, '  ')}\n  public var ${entry.identifier}: ${type}?`,
        ...(entry.transition
          ? [
              `${swiftDoc(`How \`${entry.identifier}\` changes when it is set.`, '  ')}\n  public var ${entry.identifier}Transition: TileflowTransition?`,
            ]
          : []),
      ];
    });
    const parameters = layer.source ? 'id: String, source: String' : 'id: String';
    const encode = [
      ...layer.properties.map(
        (entry) =>
          `    style.${entry.kind}(${JSON.stringify(entry.name)}, ${entry.identifier})${
            entry.transition
              ? `\n    style.${entry.kind}(${JSON.stringify(`${entry.name}-transition`)}, ${entry.identifier}Transition)`
              : ''
          }`,
      ),
    ];
    return `${swiftDoc(`${layer.documentation} MapLibre layer type \`${layer.type}\`.`, '')}
public struct ${layer.name}: TileflowLayer, Equatable {
  public static let type = ${JSON.stringify(layer.type)}
${[...fields, ...properties].join('\n')}

  public init(${parameters}) {
    self.id = id${layer.source ? '\n    self.source = source' : ''}
  }

  public func encode(to encoder: any Encoder) throws {
    var style = StyleLayerEncoding(id: id, type: Self.type)
    ${layer.source ? 'style.source = source' : ''}${layer.features ? '\n    style.sourceLayer = sourceLayer\n    style.filter = filter' : ''}
    style.minZoom = minZoom
    style.maxZoom = maxZoom
${encode.join('\n')}
    try style.encode(to: encoder)
  }
}`.replace('\n    \n', '\n');
  });
  return `${banner(version)}
import Foundation

${[...enums, ...layers].join('\n\n')}
`;
}

function swiftExpressions(model, version) {
  const operator = (entry, kind) =>
    `${swiftDoc(`${entry.documentation || `The \`${entry.name}\` ${kind}.`} MapLibre ${kind} \`${entry.name}\`.`, '  ')}
  public static func ${entry.identifier}(_ arguments: TileflowExpression...) -> TileflowExpression {
    TileflowExpression(operator: ${JSON.stringify(entry.name)}, arguments)
  }`;
  return `${banner(version)}
import Foundation

extension TileflowExpression {
${[
  ...model.operators.map((entry) => operator(entry, 'expression')),
  ...model.interpolations.map((entry) => operator(entry, 'interpolation')),
].join('\n\n')}
}
`;
}

function kotlinLayers(model, version) {
  const enums = model.enums.map(
    (entry) => `${kotlinDoc(`Values of \`${entry.property}\`.`, '')}
public enum class ${entry.name}(override val value: String) : TileflowStyleEnum {
${entry.values
  .map(
    (value) =>
      `${value.documentation ? `${kotlinDoc(value.documentation, '    ')}\n` : ''}    ${constant(value.value)}(${JSON.stringify(value.value)}),`,
  )
  .join('\n')}
}`,
  );
  const layers = model.layers.map((layer) => {
    const self = layer.name;
    const fields = [
      ...(layer.features
        ? [
            `${kotlinDoc('The layer of a vector source to draw.', '    ')}\n    public var sourceLayer: String? = null`,
            `${kotlinDoc('Draws only the features this expression accepts.', '    ')}\n    public var filter: TileflowExpression? = null`,
          ]
        : []),
      `${kotlinDoc('The zoom level from which the layer shows.', '    ')}\n    public var minZoom: Double? = null`,
      `${kotlinDoc('The zoom level from which the layer hides.', '    ')}\n    public var maxZoom: Double? = null`,
    ];
    const properties = layer.properties.flatMap((entry) => {
      const type = entry.expression ? `TileflowValue<${entry.type.kotlin}>` : entry.type.kotlin;
      const setters = entry.expression
        ? [
            `    public fun ${entry.identifier}(value: ${entry.type.kotlin}): ${self} = apply {\n        ${entry.identifier} = TileflowValue.constant(value)\n    }`,
            `    public fun ${entry.identifier}(expression: TileflowExpression): ${self} = apply {\n        ${entry.identifier} = TileflowValue.expression(expression)\n    }`,
          ]
        : [
            `    public fun ${entry.identifier}(value: ${entry.type.kotlin}): ${self} = apply {\n        ${entry.identifier} = value\n    }`,
          ];
      return [
        `${kotlinDoc(entry.documentation, '    ')}\n    public var ${entry.identifier}: ${type}? = null\n\n${setters.join('\n\n')}`,
        ...(entry.transition
          ? [
              `${kotlinDoc(`How [${entry.identifier}] changes when it is set.`, '    ')}\n    public var ${entry.identifier}Transition: TileflowTransition? = null\n\n    public fun ${entry.identifier}Transition(transition: TileflowTransition): ${self} = apply {\n        ${entry.identifier}Transition = transition\n    }`,
            ]
          : []),
      ];
    });
    const json = layer.properties.map(
      (entry) =>
        `                ${JSON.stringify(entry.name)} to ${entry.identifier},${
          entry.transition
            ? `\n                ${JSON.stringify(`${entry.name}-transition`)} to ${entry.identifier}Transition,`
            : ''
        }`,
    );
    const byKind = (kind) =>
      layer.properties
        .map((entry, index) => ({entry, line: json[index]}))
        .filter(({entry}) => entry.kind === kind)
        .map(({line}) => line)
        .join('\n');
    return `${kotlinDoc(`${layer.documentation} MapLibre layer type \`${layer.type}\`.`, '')}
public class ${self}(id: String${layer.source ? ', public val source: String' : ''}) : TileflowLayer(id, ${JSON.stringify(layer.type)}) {
${[...fields, ...properties].join('\n\n')}

    public fun minZoom(value: Double): ${self} = apply { minZoom = value }

    public fun maxZoom(value: Double): ${self} = apply { maxZoom = value }

    public fun slot(value: TileflowLayerSlot?): ${self} = apply { slot = value }
${
  layer.features
    ? `
    public fun sourceLayer(value: String): ${self} = apply { sourceLayer = value }

    public fun filter(expression: TileflowExpression): ${self} = apply { filter = expression }
`
    : ''
}
    override fun json(): org.json.JSONObject =
        styleLayerJson(
            this,
            ${layer.source ? 'source' : 'null'},
            ${layer.features ? 'sourceLayer' : 'null'},
            ${layer.features ? 'filter' : 'null'},
            minZoom,
            maxZoom,
            layout =
                listOf(
${byKind('layout')}
                ),
            paint =
                listOf(
${byKind('paint')}
                ),
        )
}`;
  });
  return `${banner(version)}
@file:Suppress("unused", "MemberVisibilityCanBePrivate")

package dev.tileflow.sdk

${[...enums, ...layers].join('\n\n')}
`;
}

function kotlinExpressions(model, version) {
  const operator = (entry, kind) =>
    `${kotlinDoc(`${entry.documentation || `The \`${entry.name}\` ${kind}.`} MapLibre ${kind} \`${entry.name}\`.`, '        ')}
        public fun ${entry.identifier}(vararg arguments: TileflowExpression): TileflowExpression =
            TileflowExpression(${JSON.stringify(entry.name)}, arguments)`;
  return `${banner(version)}
package dev.tileflow.sdk

import org.json.JSONArray
import org.json.JSONObject
import org.json.JSONTokener

/**
 * A MapLibre style expression: a value computed for each feature, zoom level or feature state.
 * Build one from the operator factories, such as \`get\`, \`match\` and \`interpolate\`, from
 * literals, or from MapLibre JSON with [fromJson].
 */
public class TileflowExpression internal constructor(internal val json: Any) {
    internal constructor(
        operator: String,
        arguments: Array<out TileflowExpression>,
    ) : this(JSONArray().apply {
        put(operator)
        arguments.forEach { put(it.json) }
    })

    /** The expression as MapLibre JSON. */
    override fun toString(): String = if (json is String) JSONObject.quote(json) else json.toString()

    override fun equals(other: Any?): Boolean =
        other is TileflowExpression && other.toString() == toString()

    override fun hashCode(): Int = toString().hashCode()

    public companion object {
        /** A number. */
        public fun literal(value: Double): TileflowExpression = TileflowExpression(value)

        /** A string. */
        public fun literal(value: String): TileflowExpression = TileflowExpression(value)

        /** A boolean. */
        public fun literal(value: Boolean): TileflowExpression = TileflowExpression(value)

        /** A list of numbers, strings, booleans or nested lists, as one value. */
        public fun literal(values: List<Any?>): TileflowExpression =
            TileflowExpression(JSONArray().put("literal").put(styleConstantJson(values)))

        /** An object of numbers, strings, booleans or lists, as one value. */
        public fun literal(value: Map<String, Any?>): TileflowExpression =
            TileflowExpression(
                JSONArray().put("literal").put(JSONObject(value.mapValues { styleConstantJson(it.value) }))
            )

        /** A colour. */
        public fun color(value: TileflowColor): TileflowExpression = TileflowExpression(value.css)

        /** The value of a feature property. */
        public fun get(property: String): TileflowExpression = get(literal(property))

        /** Whether a feature has a property. */
        public fun has(property: String): TileflowExpression = has(literal(property))

        /** The value of a key of the feature's state. */
        public fun featureState(key: String): TileflowExpression = featureState(literal(key))

        /**
         * An expression in MapLibre's JSON form, such as \`["get", "name"]\`.
         *
         * @throws TileflowMapException with [TileflowErrorCode.INVALID_REQUEST] when [json] is not
         *   JSON.
         */
        public fun fromJson(json: String): TileflowExpression {
            val value =
                try {
                    val tokener = JSONTokener(json)
                    tokener.nextValue().takeIf { tokener.nextClean() == 0.toChar() }
                } catch (_: Exception) {
                    null
                }
            // org.json reads unquoted words as text; JSON does not.
            val strict =
                value is JSONArray ||
                    value is JSONObject ||
                    value is Number ||
                    value is Boolean ||
                    (value is String && json.trim().startsWith('"'))
            if (!strict) throw TileflowMapException(TileflowErrorCode.INVALID_REQUEST)
            return TileflowExpression(value!!)
        }

${[
  ...model.operators.map((entry) => operator(entry, 'expression')),
  ...model.interpolations.map((entry) => operator(entry, 'interpolation')),
].join('\n\n')}
    }
}
`;
}

/** Every generated file for a style specification. */
export function renderStyle(spec, version) {
  const model = readSpecification(spec);
  return {
    [outputs.swiftLayers]: swiftLayers(model, version),
    [outputs.swiftExpressions]: swiftExpressions(model, version),
    [outputs.kotlinLayers]: kotlinLayers(model, version),
    [outputs.kotlinExpressions]: kotlinExpressions(model, version),
  };
}
